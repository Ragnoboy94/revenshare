import { FAQ_ITEMS } from "@/lib/faq";
import { IP } from "@/lib/ip";
import { SEO, siteBaseUrl } from "@/lib/seo";

function link(label: string, url: string, note?: string): string {
  return note ? `- [${label}](${url}): ${note}` : `- [${label}](${url})`;
}

/** Курсорный индекс для LLM (спека llmstxt.org) — как у Нависерта. */
export function buildLlmsTxt(): string {
  const base = siteBaseUrl();

  return [
    `# ${IP.brand}`,
    "",
    `> ${SEO.description}`,
    "",
    `${IP.brand} — модель revenue share на разработку сайтов для бизнеса с онлайн-заявками (услуги, медицина, ремонт, B2B, сертификация и др.). Юрлицо: ${IP.fullName}, ИНН ${IP.inn}, ОГРНИП ${IP.ogrnip}, ${IP.city}.`,
    "",
    "Для подробного контекста см. [llms-full.txt](/llms-full.txt).",
    "",
    "## Главное",
    "",
    link("Главная", `${base}/`, "Оффер и как работает модель"),
    link("Как это работает", `${base}/#how`, "Демостенд, договор, хостинг, сверка"),
    link("Условия", `${base}/#terms`, "10%, выкуп 29 000 ₽, хостинг 3 мес"),
    link("Кому подходит", `${base}/#fit`, "Фильтр подходит / не подходит"),
    link("Кейс", `${base}/#case`, `Пример: ${IP.caseName}`),
    link("FAQ", `${base}/#faq`, "Предоплата, демо, код, выкуп"),
    link("Заявка", `${base}/#lead`, "Форма обсуждения проекта"),
    "",
    "## Optional",
    "",
    link("Политика конфиденциальности", `${base}/privacy`),
    link("Sitemap", `${base}/sitemap.xml`),
    link("robots.txt", `${base}/robots.txt`),
    link("Полный контекст для LLM", `${base}/llms-full.txt`),
    "",
  ].join("\n");
}

/** Развёрнутый контекст для LLM. */
export function buildLlmsFullTxt(): string {
  const base = siteBaseUrl();

  const parts: string[] = [
    `# ${IP.brand} — полный контекст для LLM`,
    "",
    `> ${SEO.ogDescription}`,
    "",
    "## О компании",
    "",
    `- Бренд: ${IP.brand}`,
    `- Юрлицо: ${IP.fullName}`,
    `- ИНН: ${IP.inn}`,
    `- ОГРНИП: ${IP.ogrnip}`,
    `- Город: ${IP.city}, ${IP.region}`,
    `- НДС: ${IP.tax}`,
    `- ОКД: ${IP.okved} (${IP.okvedName})`,
    `- Email: ${IP.email}`,
    `- Сайт: ${base}`,
    "",
    "## Что делаем",
    "",
    "- Разрабатываем продающие сайты без предоплаты под брендом RevenShare (ИП)",
    "- До договора — демостенд с правками дизайна и функционала",
    "- После договора — публикация, хостинг 3 месяца за наш счёт; домен у клиента",
    "- Клиент платит 10% со всех заявок клиентов, пришедших с сайта, включая повторные",
    "- Если через 3 месяца заявок с сайта нет — выкуп за 29 000 ₽",
    "- Код принадлежит RevenShare; контент и бренд — клиента",
    "- Реклама и SEO не входят в базовый оффер — отдельно",
    "",
    "## Кому подходит",
    "",
    "- Бизнес с заявками онлайн: услуги, медицина, ремонт, B2B",
    "- Маржа позволяет отдавать 10% с заявки клиента с сайта",
    "- Готовность к учёту источников (Метрика / CRM) и ежемесячной сверке",
    "",
    "## Кому не подходит",
    "",
    "- Продажи только офлайн без учёта заявок с сайта",
    "- Очень низкий чек — процент с заявки экономически не тянется",
    "- «Сайт ради сайта» без продаж и прозрачности",
    "",
    "## Как это работает",
    "",
    "1. Созвон: ниша, спрос, подходит ли модель",
    "2. Демостенд: сборка сайта, правки дизайна и функций до договора",
    "3. Договор: 10%, атрибуция, хостинг, выкуп",
    "4. Публикация: хостинг 3 месяца за наш счёт, домен у клиента",
    "5. Развитие и сверка: правки по запросу; раз в месяц % с заявок с сайта",
    "",
    "## Кейс",
    "",
    `Центр сертификации «Нависерт» — ${IP.caseUrl}`,
    "Сайт с понятной подачей услуг и заявками.",
    "",
    "## FAQ",
    "",
  ];

  for (const item of FAQ_ITEMS) {
    parts.push(`### ${item.q}`, "", item.a, "");
  }

  parts.push(
    "## Контакты",
    "",
    `Заявка на сайте: ${base}/#lead`,
    `Email: ${IP.email}`,
    `Политика ПДн: ${base}/privacy`,
    ""
  );

  return `${parts.join("\n")}\n`;
}

export function llmsTxtResponse(body: string): Response {
  return new Response(body, {
    headers: {
      "Content-Type": "text/plain; charset=utf-8",
      "Cache-Control": "public, s-maxage=3600, stale-while-revalidate=86400",
    },
  });
}
